"""Generate frontend/src/api/types.ts from backend/vaultai/domain.py.

The pydantic models are the API contract; the TypeScript mirror is derived so
the two cannot drift. Run after editing domain.py:

    backend/.venv/bin/python scripts/gen_types.py          # write
    backend/.venv/bin/python scripts/gen_types.py --check  # exit 1 if stale
"""

from __future__ import annotations

import sys
import types
import typing
from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from pydantic import BaseModel  # noqa: E402
from pydantic_core import PydanticUndefined  # noqa: E402

from vaultai import domain  # noqa: E402

OUT = ROOT / "frontend" / "src" / "api" / "types.ts"

# Request bodies: fields with defaults are optional for the caller.
REQUEST_MODELS = {
    "ProcessRequest", "FieldEdit", "ReviewRequest", "BatchReviewRequest", "ObligationUpdate",
    "ExportFilters", "ScanRequest", "PageEdit", "AssembleRequest", "DeleteAllRequest",
}


def ts_type(tp: object) -> str:
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if tp is type(None):
        return "null"
    if tp is str or tp is Decimal or tp is date or tp is datetime:
        return "string"
    if tp is int or tp is float:
        return "number"
    if tp is bool:
        return "boolean"
    if tp is domain.Box:
        return "Box"
    if isinstance(tp, type) and issubclass(tp, StrEnum):
        return tp.__name__
    if isinstance(tp, type) and issubclass(tp, BaseModel):
        return tp.__name__
    if origin is typing.Literal:
        return " | ".join(f'"{a}"' if isinstance(a, str) else str(a) for a in args)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(ts_type(a) for a in args)
    if origin is list:
        inner = ts_type(args[0])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if origin is tuple:
        return "[" + ", ".join(ts_type(a) for a in args) + "]"
    if origin is dict:
        return f"Record<{ts_type(args[0])}, {ts_type(args[1])}>"
    raise TypeError(f"no TypeScript mapping for {tp!r}")


def render() -> str:
    out = [
        "// GENERATED by scripts/gen_types.py from backend/vaultai/domain.py. Do not edit.",
        "",
        f'export const SCHEMA_VERSION = "{domain.SCHEMA_VERSION}";',
        "",
        "export type Box = [number, number, number, number];",
        "",
    ]
    members = vars(domain)
    # dict.fromkeys dedupes module-level aliases such as `_S = DocStatus`.
    enums = list(dict.fromkeys(
        v for v in members.values() if isinstance(v, type) and issubclass(v, StrEnum) and v.__module__ == domain.__name__
    ))
    for enum in enums:
        values = [m.value for m in enum]
        out.append(f"export type {enum.__name__} = " + " | ".join(f'"{v}"' for v in values) + ";")
        out.append(f"export const {enum.__name__}Values: {enum.__name__}[] = [" + ", ".join(f'"{v}"' for v in values) + "];")
        out.append("")
    out.append("export const DOC_TYPE_LABELS: Record<DocType, string> = {")
    for k, label in domain.DOC_TYPE_LABELS.items():
        out.append(f'  {k.value}: "{label}",')
    out.append("};")
    out.append("")
    out.append("export const LEGAL_DOC_TYPES: DocType[] = [" + ", ".join(f'"{t.value}"' for t in sorted(domain.LEGAL_DOC_TYPES)) + "];")
    out.append("")

    models = list(dict.fromkeys(
        v for v in members.values() if isinstance(v, type) and issubclass(v, domain.ApiModel) and v is not domain.ApiModel
    ))
    for model in models:
        parent = model.__mro__[1]
        own = model.__annotations__.keys() if parent is not domain.ApiModel else None
        extends = f" extends {parent.__name__}" if parent is not domain.ApiModel else ""
        out.append(f"export interface {model.__name__}{extends} {{")
        hints = typing.get_type_hints(model)
        for name, info in model.model_fields.items():
            if own is not None and name not in own:
                continue
            has_default = info.default is not PydanticUndefined or info.default_factory is not None
            optional = "?" if has_default and model.__name__ in REQUEST_MODELS else ""
            out.append(f"  {name}{optional}: {ts_type(hints[name])};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/gen_types.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
